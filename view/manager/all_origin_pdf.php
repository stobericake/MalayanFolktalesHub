<?php
session_start();
require('../../fpdf/fpdf.php'); // Include the FPDF library

// Database connection
include '../dbconn.php';

// Fetch all genres
$stateQuery = "SELECT state, COUNT(*) AS total_folktales 
               FROM folktales 
               GROUP BY state";
$stateResult = $conn->query($stateQuery);

// Create PDF
$pdf = new FPDF();
$pdf->AddPage();
$pdf->SetFont('Times', 'B', 16);
$pdf->SetTextColor(0, 0, 0);

// Loop through each genre
while ($stateData = $stateResult->fetch_assoc()) {
    $state = $stateData['state'];

    // Fetch folktale titles for the current genre
    $folktaleQuery = "SELECT title, genre 
                      FROM folktales 
                      WHERE state = ?";
    $stmt = $conn->prepare($folktaleQuery);
    $stmt->bind_param("s", $state);
    $stmt->execute();
    $folktaleResult = $stmt->get_result();

    // Genre Section Title
    $pdf->SetFont('Times', 'B', 16);
    $pdf->Cell(0, 10, 'State Report: ' . $stateData['state'], 0, 1, 'C');
    $pdf->Ln(5);

    // Genre Details
    $pdf->SetFont('Times', '', 12);
    $pdf->Cell(0, 10, 'Total Folktales: ' . $stateData['total_folktales'], 0, 1);
    $pdf->Ln(3);

    // Folktales Table
    $pdf->SetFont('Times', 'B', 12);
    $pdf->SetFillColor(0, 0, 0); // Header background color
    $pdf->SetTextColor(255, 255, 255); // White text color

    $pdf->Cell(20, 10, 'No.', 1, 0, 'C', true);
    $pdf->Cell(100, 10, 'Folktale Title', 1, 0, 'L', true);
    $pdf->Cell(70, 10, 'Genre', 1, 1, 'L', true);

    $pdf->SetFont('Times', '', 12);
    $pdf->SetTextColor(0, 0, 0); // Reset text color

    if ($folktaleResult->num_rows > 0) {
        $counter = 1;
        while ($row = $folktaleResult->fetch_assoc()) {
            $pdf->SetFillColor(255, 255, 255); // Alternate row background
            $pdf->Cell(20, 10, $counter, 1, 0, 'C', true);
            $pdf->Cell(100, 10, $row['title'], 1, 0, 'L', true);
            $pdf->Cell(70, 10, $row['genre'], 1, 1, 'L', true);
            $counter++;
        }
    } else {
        $pdf->Cell(0, 10, 'No folktales found for this genre.', 1, 1);
    }
    $pdf->Ln(10); // Add extra space between genre sections
}

// Footer
$pdf->SetFont('Times', 'I', 10);
$pdf->Cell(0, 10, 'Report Generated By: Malayan Folktales Hub - UiTM Kuala Terengganu', 0, 1);
$pdf->Cell(0, 10, 'Date of Report: ' . date('F j, Y'), 0, 1);

// Output the PDF
$pdf->Output('D', 'All_State_Report.pdf');
?>