<?php
session_start();
require('../../fpdf/fpdf.php');
include '../dbconn.php';

if (isset($_GET['origin'])) {
    $state = $_GET['origin'];

    $stateQuery = "SELECT state, COUNT(*) AS total_folktales 
                   FROM folktales 
                   WHERE state = ? 
                   GROUP BY state";
    $stmt = $conn->prepare($stateQuery);
    $stmt->bind_param("s", $state);
    $stmt->execute();
    $stateResult = $stmt->get_result();
    $stateData = $stateResult->fetch_assoc();

    $folktaleQuery = "SELECT title, genre FROM folktales WHERE state = ?";
    $stmt = $conn->prepare($folktaleQuery);
    $stmt->bind_param("s", $state);
    $stmt->execute();
    $folktaleResult = $stmt->get_result();

    $pdf = new FPDF();
    $pdf->AddPage();
    $pdf->SetFont('Times', 'B', 16);

    $pdf->SetTextColor(0, 0, 0); 
    $pdf->Cell(0, 10, 'State Report: ' . $stateData['state'], 0, 1, 'C');
    $pdf->Ln(8);

    $pdf->SetFont('Times', '', 12);
    $pdf->SetTextColor(0, 0, 0);
    $pdf->Cell(0, 10, 'Total Folktales: ' . $stateData['total_folktales'], 0, 1);
    $pdf->Ln(5);

    $pdf->SetFont('Times', 'B', 12);
    $pdf->SetFillColor(0, 0, 0);
    $pdf->SetTextColor(255, 255, 255);

    $pdf->Cell(20, 10, 'No.', 1, 0, 'C', true);
    $pdf->Cell(100, 10, 'Folktale Title', 1, 0, 'L', true);
    $pdf->Cell(70, 10, 'Genre', 1, 1, 'L', true); 

    $pdf->SetFont('Times', '', 12);
    $pdf->SetTextColor(0, 0, 0);

    if ($folktaleResult->num_rows > 0) {
        $counter = 1;
        while ($row = $folktaleResult->fetch_assoc()) {
            $pdf->SetFillColor(255, 255, 255);
            $pdf->Cell(20, 10, $counter, 1, 0, 'C', true);
            $pdf->Cell(100, 10, $row['title'], 1, 0, 'L', true);
            $pdf->Cell(70, 10, $row['genre'], 1, 1, 'L', true);
            $counter++;
        }
    } else {
        $pdf->Cell(0, 10, 'No folktales found for this state.', 1, 1);
    }
    $pdf->Ln(5);

    $pdf->SetFont('Times', 'I', 10);
    $pdf->Cell(0, 10, 'Report Generated By: Malayan Folktales Hub - UiTM Kuala Terengganu', 0, 1);
    $pdf->Cell(0, 10, 'Date of Report: ' . date('F j, Y'), 0, 1);

    $pdf->Output('D', 'State_Report_' . $stateData['state'] . '.pdf'); 
} else {
    echo "Invalid request.";
}
?>
