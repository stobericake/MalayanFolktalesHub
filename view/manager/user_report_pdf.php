<?php
session_start();
require('../../fpdf/fpdf.php');
include '../dbconn.php';

if (isset($_GET['userID'])) {
    $userID = $_GET['userID'];

    $userQuery = "SELECT name, email FROM user WHERE userID = ?";
    $stmt = $conn->prepare($userQuery);
    $stmt->bind_param("i", $userID);
    $stmt->execute();
    $userResult = $stmt->get_result();
    $user = $userResult->fetch_assoc();

    $statsQuery = "SELECT 
                    COALESCE((SELECT COUNT(*) 
                              FROM bookmark b 
                              JOIN bookmark_folktale bf ON b.bookmark_folktaleID = bf.bookmark_folktaleID 
                              WHERE b.userID = ?), 0) AS total_bookmarks, 
                    COALESCE(COUNT(c.commentID), 0) AS total_comments 
                   FROM user u 
                   LEFT JOIN comment c ON u.userID = c.userID 
                   WHERE u.userID = ?";
    $stmt = $conn->prepare($statsQuery);
    $stmt->bind_param("ii", $userID, $userID);
    $stmt->execute();
    $statsResult = $stmt->get_result();
    $stats = $statsResult->fetch_assoc();

    $bookmarkQuery = "SELECT f.title, f.state FROM bookmark b 
                      JOIN bookmark_folktale bf ON b.bookmark_folktaleID = bf.bookmark_folktaleID 
                      JOIN folktales f ON bf.folktaleID = f.folktaleID 
                      WHERE b.userID = ?";
    $stmt = $conn->prepare($bookmarkQuery);
    $stmt->bind_param("i", $userID);
    $stmt->execute();
    $bookmarkResult = $stmt->get_result();

    $commentQuery = "SELECT c.content, f.title FROM comment c 
                     JOIN folktales f ON c.folktaleID = f.folktaleID 
                     WHERE c.userID = ?";
    $stmt = $conn->prepare($commentQuery);
    $stmt->bind_param("i", $userID);
    $stmt->execute();
    $commentResult = $stmt->get_result();

    $pdf = new FPDF();
    $pdf->AddPage();
    $pdf->SetFont('Times', 'B', 16);
    $pdf->SetTextColor(0, 0, 0);
    
    $pdf->Cell(0, 10, 'User Report: ' . $user['name'], 0, 1, 'C');
    $pdf->Ln(8);

    $pdf->SetFont('Times', '', 12);
    $pdf->Cell(0, 10, 'Email: ' . $user['email'], 0, 1);
    $pdf->Cell(0, 10, 'Total Bookmarks: ' . $stats['total_bookmarks'], 0, 1);
    $pdf->Ln(5);

    $pdf->SetFont('Times', 'B', 12);
    $pdf->SetFillColor(0, 0, 0);
    $pdf->SetTextColor(255, 255, 255);
    $pdf->Cell(10, 10, 'No.', 1, 0, 'C', true);
    $pdf->Cell(90, 10, 'Folktale Title', 1, 0, 'L', true);
    $pdf->Cell(90, 10, 'Origin', 1, 1, 'L', true); // Adjust width to fit properly

    $pdf->SetFont('Times', '', 12);
    $pdf->SetTextColor(0, 0, 0);
    if ($bookmarkResult->num_rows > 0) {
        $counter = 1;
        while ($row = $bookmarkResult->fetch_assoc()) {
            $pdf->SetFillColor(255, 255, 255);
            $pdf->Cell(10, 10, $counter, 1, 0, 'C', true);
            $pdf->Cell(90, 10, $row['title'], 1, 0, 'L', true);
            $pdf->Cell(90, 10, $row['state'], 1, 1, 'L', true);
            $counter++;
        }
    } else {
        $pdf->Cell(0, 10, 'No bookmarks found.', 1, 1);
    }
    $pdf->Ln(5);

    $pdf->SetFont('Times', '', 12);
    $pdf->Cell(0, 10, 'Total Comments: ' . $stats['total_comments'], 0, 1);
    $pdf->Ln(5);

    $pdf->SetFont('Times', 'B', 12);
    $pdf->SetFillColor(0, 0, 0);
    $pdf->SetTextColor(255, 255, 255);
    $pdf->Cell(10, 10, 'No.', 1, 0, 'C', true);
    $pdf->Cell(90, 10, 'Folktale Title', 1, 0, 'L', true);
    $pdf->Cell(90, 10, 'Comment', 1, 1, 'L', true);
    
    $pdf->SetFont('Times', '', 12);
    $pdf->SetTextColor(0, 0, 0);
    if ($commentResult->num_rows > 0) {
        $counter = 1;
        while ($row = $commentResult->fetch_assoc()) {
            $pdf->Cell(10, 10, $counter, 1, 0, 'C');
            $pdf->Cell(90, 10, $row['title'], 1, 0, 'L');
            $pdf->Cell(90, 10, substr($row['content'], 0, 30) . '...', 1, 1, 'L');
            $counter++;
        }
    } else {
        $pdf->Cell(0, 10, 'No comments found.', 1, 1);
    }
    $pdf->Ln(5);
    $pdf->SetFont('Times', 'I', 10);
    $pdf->Cell(0, 10, 'Report Generated By: Malayan Folktales Hub - UiTM Kuala Terengganu', 0, 1);
    $pdf->Cell(0, 10, 'Date of Report: ' . date('F j, Y'), 0, 1);

    $pdf->Output('D', 'User_Report_' . $user['name'] . '.pdf');
} else {
    echo "Invalid request.";
}
?>