<?php
session_start();
require('../../fpdf/fpdf.php'); 
include '../dbconn.php';

if (isset($_GET['genre'])) {
    $genre = $_GET['genre'];

    $genreQuery = "SELECT genre, COUNT(*) AS total_folktales 
                   FROM folktales 
                   WHERE genre = ? 
                   GROUP BY genre";
    $stmt = $conn->prepare($genreQuery);
    $stmt->bind_param("s", $genre);
    $stmt->execute();
    $genreResult = $stmt->get_result();
    $genreData = $genreResult->fetch_assoc();

    $folktaleQuery = "SELECT title , state
                      FROM folktales 
                      WHERE genre = ?";
    $stmt = $conn->prepare($folktaleQuery);
    $stmt->bind_param("s", $genre);
    $stmt->execute();
    $folktaleResult = $stmt->get_result();

    $pdf = new FPDF();
    $pdf->AddPage();
    $pdf->SetFont('Times', 'B', 16);

    $pdf->SetTextColor(0, 0, 0); 
    $pdf->Cell(0, 10, 'Genre Report: '. $genreData['genre'], 0, 1, 'C');
    $pdf->Ln(8);

    $pdf->SetFont('Times', '', 12);
    $pdf->SetTextColor(0, 0, 0); 
    $pdf->Cell(0, 10, 'Total Folktales: ' . $genreData['total_folktales'], 0, 1);
    $pdf->Ln(5);

    $pdf->SetFont('Times', 'B', 12);
    $pdf->SetFillColor(0, 0, 0);
    $pdf->SetTextColor(255, 255, 255); 

    $pdf->Cell(20, 10, 'No.', 1, 0, 'C', true);
    $pdf->Cell(100, 10, 'Folktale Title', 1, 0, 'L', true);
    $pdf->Cell(70, 10, 'Origin', 1, 1, 'L', true); 


    $pdf->SetFont('Times', '', 12);
    $pdf->SetTextColor(0, 0, 0); 

    if ($folktaleResult->num_rows > 0) {
        $counter = 1;
        $alternate = false;
        while ($row = $folktaleResult->fetch_assoc()) {
            $pdf->SetFillColor(255, 255, 255); 
            $pdf->Cell(20, 10, $counter, 1, 0, 'C', true);
            $pdf->Cell(100, 10, $row['title'], 1, 0, 'L', true);
            $pdf->Cell(70, 10, $row['state'], 1, 1, 'L', true);
            $alternate = !$alternate;
            $counter++;
        }
    } else {
        $pdf->Cell(0, 10, 'No folktales found for this genre.', 1, 1);
    }
    $pdf->Ln(5);

    $pdf->SetFont('Times', 'I', 10);
    $pdf->Cell(0, 10, 'Report Generated By: Malayan Folktales Hub - UiTM Kuala Terengganu', 0, 1);
    $pdf->Cell(0, 10, 'Date of Report: ' . date('F j, Y'), 0, 1);

    $pdf->Output('D', 'Genre_Report_' . $genreData['genre'] . '.pdf');
} else {
    echo "Invalid request.";
}
?>
